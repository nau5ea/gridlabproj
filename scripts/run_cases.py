#!/usr/bin/env python3
"""Run the GridLAB-D ZIP and transformer-candidate cases.

GridLAB-D's ``#define`` is a GLM preprocessor directive, not the same as the
command-line ``-D`` global setter.  This runner therefore writes a tiny wrapper
GLM for each (case, transformer rating) pair and invokes GridLAB-D from the
repository root.

Examples
--------
    python3 scripts/run_cases.py --case mixed --xfmr 25
    python3 scripts/run_cases.py --all-candidates
    python3 scripts/run_cases.py --cases all --xfmr 37.5
"""

from __future__ import annotations

import argparse
import csv
import os
import shutil
import subprocess
import sys
from datetime import datetime
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
GLM_DIR = ROOT / "glm"
CASE_DIR = GLM_DIR / "cases"
GENERATED_DIR = CASE_DIR / "generated"
OUTPUT_DIR = ROOT / "outputs"
LOG_DIR = OUTPUT_DIR / "logs"

CASES = {
    "constant_power": dict(power=1.0, current=0.0, impedance=0.0),
    "constant_current": dict(power=0.0, current=1.0, impedance=0.0),
    "constant_impedance": dict(power=0.0, current=0.0, impedance=1.0),
    "mixed": dict(power=0.30, current=0.30, impedance=0.40),
}

DEFAULT_CANDIDATES_KVA = [10.0, 15.0, 25.0, 37.5]


def find_gridlabd(explicit: str | None) -> str:
    if explicit:
        return explicit
    env = os.environ.get("GRIDLABD")
    if env:
        return env
    found = shutil.which("gridlabd")
    if found:
        return found
    # Convenient fallback for the development environment used to build this
    # skeleton: a sibling GridLAB-D source/build tree.
    sibling = ROOT.parent / "gridlab-d" / "cmake-build" / "bin" / "gridlabd"
    if sibling.exists():
        return str(sibling)
    raise SystemExit(
        "GridLAB-D was not found.  Put gridlabd on PATH, set GRIDLABD, or pass "
        "--gridlabd /path/to/gridlabd."
    )


def ensure_players() -> None:
    required = [ROOT / "data" / "players" / f"house{index}_{kind}.player"
                for index in (1, 2, 3) for kind in ("load", "water")]
    if all(path.exists() for path in required):
        return
    print("Player files missing; preparing players from the supplied house profiles.")
    subprocess.run([sys.executable, str(ROOT / "scripts" / "prepare_real_profiles.py")], check=True)


def write_wrapper(case: str, xfmr_kva: float) -> Path:
    fractions = CASES[case]
    text = f"""// Auto-generated by scripts/run_cases.py -- do not edit.
#define CASE_NAME={case}
#define ZIP_POWER_FRACTION={fractions['power']}
#define ZIP_CURRENT_FRACTION={fractions['current']}
#define ZIP_IMPEDANCE_FRACTION={fractions['impedance']}
#define XFMR_KVA={xfmr_kva:g}
#include "glm/model.glm"
"""
    GENERATED_DIR.mkdir(parents=True, exist_ok=True)
    path = GENERATED_DIR / f"run_{case}_xfmr{xfmr_kva:g}kva.glm"
    path.write_text(text, encoding="utf-8")
    return path


def output_prefix(case: str, xfmr_kva: float) -> str:
    return f"{case}_xfmr{xfmr_kva:g}kva"


def run_one(gridlabd: str, case: str, xfmr_kva: float) -> dict:
    wrapper = write_wrapper(case, xfmr_kva)
    log_path = LOG_DIR / f"{output_prefix(case, xfmr_kva)}.log"
    command = [gridlabd, "-W", str(ROOT), str(wrapper)]
    started = datetime.now().isoformat(timespec="seconds")
    try:
        completed = subprocess.run(
            command, cwd=ROOT, capture_output=True, text=True, timeout=1800
        )
        exit_code = completed.returncode
        log_text = completed.stdout + completed.stderr
    except subprocess.TimeoutExpired as exc:
        exit_code = 124
        log_text = (exc.stdout or "") + (exc.stderr or "") + "\nTIMEOUT\n"

    log_path.write_text(log_text)
    status = "PASS" if exit_code == 0 else "FAIL"
    print(f"  {status:4s} {case:18s} xfmr={xfmr_kva:5g} kVA  -> {log_path.relative_to(ROOT)}")
    return {
        "case": case,
        "xfmr_kva": xfmr_kva,
        "prefix": output_prefix(case, xfmr_kva),
        "exit_code": exit_code,
        "status": status,
        "started": started,
        "log": str(log_path.relative_to(ROOT)),
        "command": " ".join(command),
    }


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--case", choices=sorted(CASES), help="Run one ZIP case.")
    parser.add_argument("--cases", default=None,
                        help="Comma-separated ZIP cases, or 'all'.")
    parser.add_argument("--xfmr", type=float, default=25.0,
                        help="Transformer rating in kVA (default: 25).")
    parser.add_argument("--candidates", default=None,
                        help="Comma-separated candidate ratings for --all-candidates.")
    parser.add_argument("--all-candidates", action="store_true",
                        help="Run every candidate rating for the selected cases.")
    parser.add_argument("--gridlabd", default=None, help="Path to the GridLAB-D executable.")
    parser.add_argument("--append-manifest", action="store_true",
                        help="Append to outputs/runs.csv instead of replacing it.")
    args = parser.parse_args()

    if args.case:
        cases = [args.case]
    elif args.cases:
        cases = sorted(CASES) if args.cases == "all" else [c.strip() for c in args.cases.split(",") if c.strip()]
    else:
        cases = sorted(CASES)
    bad = [case for case in cases if case not in CASES]
    if bad:
        raise SystemExit(f"Unknown case(s): {', '.join(bad)}")

    if args.all_candidates:
        candidates = DEFAULT_CANDIDATES_KVA
        if args.candidates:
            candidates = [float(value) for value in args.candidates.split(",")]
    else:
        candidates = [args.xfmr]

    gridlabd = find_gridlabd(args.gridlabd)
    ensure_players()
    LOG_DIR.mkdir(parents=True, exist_ok=True)
    OUTPUT_DIR.mkdir(parents=True, exist_ok=True)

    print(f"GridLAB-D: {gridlabd}")
    print(f"Cases: {', '.join(cases)}")
    print(f"Candidates: {', '.join(f'{value:g}' for value in candidates)} kVA")

    records = [run_one(gridlabd, case, xfmr) for case in cases for xfmr in candidates]

    manifest = OUTPUT_DIR / "runs.csv"
    fieldnames = ["case", "xfmr_kva", "prefix", "exit_code", "status", "started", "log", "command"]
    mode = "a" if args.append_manifest and manifest.exists() else "w"
    with manifest.open(mode, newline="", encoding="utf-8") as handle:
        writer = csv.DictWriter(handle, fieldnames=fieldnames)
        if mode == "w":
            writer.writeheader()
        writer.writerows(records)

    failures = [record for record in records if record["exit_code"] != 0]
    print(f"\nWrote {manifest.relative_to(ROOT)} ({len(records)} runs, {len(failures)} failed).")
    if failures:
        raise SystemExit(1)


if __name__ == "__main__":
    main()
